static gboolean mf_english;
static const char *tr(const char *s) {
  if (!mf_english || !s) return s;
  for (gsize i = 0; i < G_N_ELEMENTS(mf_messages); i++)
    if (!strcmp(s, mf_messages[i].ru)) return mf_messages[i].en;
  return s;
}
static const char *tr_service_error(const char *s) {
  if (mf_english || !s) return s;
  for (gsize i = 0; i < G_N_ELEMENTS(mf_service_errors); i++)
    if (!strcmp(s, mf_service_errors[i].en)) return mf_service_errors[i].ru;
  return s;
}
